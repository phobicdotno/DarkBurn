/// Recomputed cached geometry of a contour.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Measure {
    /// Path length.
    pub length: f64,
    /// Bounding box minimum.
    pub bbox_min: Point,
    /// Bounding box maximum.
    pub bbox_max: Point,
    /// Start.
    pub start: Point,
    /// End.
    pub end: Point,
}

fn arc_pts(c: Point, r: f64, a0: f64, a1: f64, step: f64) -> Vec<Point> {
    let sweep = a1 - a0;
    let n = ((sweep.abs() * r.max(1.0) / step) as usize + 1).clamp(8, 20000);
    (0..=n)
        .map(|i| {
            let a = a0 + sweep * i as f64 / n as f64;
            Point::new(c.x + r * a.cos(), c.y + r * a.sin())
        })
        .collect()
}

fn bulge_pts(p0: Point, p1: Point, bulge: f64, step: f64) -> Vec<Point> {
    if bulge.abs() < 1e-12 {
        return vec![p0, p1];
    }
    let theta = 4.0 * bulge.atan();
    let (dx, dy) = (p1.x - p0.x, p1.y - p0.y);
    let chord = dx.hypot(dy);
    if chord < 1e-12 {
        return vec![p0, p1];
    }
    let r = chord / (2.0 * (theta.abs() / 2.0).sin());
    let (mx, my) = ((p0.x + p1.x) / 2.0, (p0.y + p1.y) / 2.0);
    let d = (r * r - (chord / 2.0).powi(2)).max(0.0).sqrt();
    let (nx, ny) = (-dy / chord, dx / chord);
    // The centre is left of the chord for a counter-clockwise minor arc; a major arc puts it on
    // the other side, otherwise the span would not end at p1.
    let (cx, cy) = if (bulge > 0.0) == (theta.abs() < std::f64::consts::PI) { (mx + nx * d, my + ny * d) } else { (mx - nx * d, my - ny * d) };
    let a0 = (p0.y - cy).atan2(p0.x - cx);
    arc_pts(Point::new(cx, cy), r, a0, a0 + theta, step)
}

fn flatten(g: &Glyph, step: f64) -> Option<Vec<Point>> {
    use std::f64::consts::PI;
    Some(match g {
        Glyph::Point(p) => vec![*p],
        Glyph::Segment { p0, p1 } => vec![*p0, *p1],
        Glyph::Arc { center, radius, start_angle, end_angle } => arc_pts(*center, *radius, *start_angle, *end_angle, step),
        Glyph::Circle { center, radius } => arc_pts(*center, *radius, 0.0, 2.0 * PI, step),
        Glyph::EllipseArc { center, major_axis, ratio, start_param, end_param } => {
            let (t0, mut t1) = (*start_param, *end_param);
            if t1 <= t0 + 1e-12 {
                t1 += 2.0 * PI;
            }
            let a = major_axis.x.hypot(major_axis.y);
            let n = (((t1 - t0) * a.max(1.0) / step) as usize + 1).clamp(16, 20000);
            let (px, py) = (-major_axis.y * ratio, major_axis.x * ratio);
            (0..=n)
                .map(|i| {
                    let t = t0 + (t1 - t0) * i as f64 / n as f64;
                    Point::new(center.x + t.cos() * major_axis.x + t.sin() * px, center.y + t.cos() * major_axis.y + t.sin() * py)
                })
                .collect()
        }
        Glyph::LwPolyline { closed, vertices } => {
            let v = vertices;
            if v.is_empty() {
                return None;
            }
            let segs = if *closed != 0 { v.len() } else { v.len() - 1 };
            let mut pts: Vec<Point> = Vec::new();
            for i in 0..segs {
                let mut seg = bulge_pts(v[i].pt, v[(i + 1) % v.len()].pt, v[i].bulge, step);
                if !pts.is_empty() {
                    seg.remove(0);
                }
                pts.extend(seg);
            }
            if pts.is_empty() {
                pts.push(v[0].pt);
            }
            pts
        }
        Glyph::Spline { .. } => return None,
    })
}

fn measure(elements: &[ContourElement], step: f64) -> Option<Measure> {
    let mut total = 0.0;
    let mut pts: Vec<Point> = Vec::new();
    let (mut first, mut last) = (None, None);
    for el in elements {
        let mut pl = flatten(&el.glyph, step)?;
        if el.direction == -1 {
            pl.reverse();
        }
        total += pl.windows(2).map(|w| (w[1] - w[0]).hypot()).sum::<f64>();
        if first.is_none() {
            first = pl.first().copied();
        }
        last = pl.last().copied();
        pts.extend(pl);
    }
    let (first, last) = (first?, last?);
    let min_x = pts.iter().map(|p| p.x).fold(f64::INFINITY, f64::min);
    let min_y = pts.iter().map(|p| p.y).fold(f64::INFINITY, f64::min);
    let max_x = pts.iter().map(|p| p.x).fold(f64::NEG_INFINITY, f64::max);
    let max_y = pts.iter().map(|p| p.y).fold(f64::NEG_INFINITY, f64::max);
    Some(Measure { length: total, bbox_min: Point::new(min_x, min_y), bbox_max: Point::new(max_x, max_y), start: first, end: last })
}

