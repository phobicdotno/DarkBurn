/// Format like MSVCR100 `printf("%.<precision>f")`: the binary value is first reduced to 17
/// significant decimal digits, then rounded half up at `precision` decimals (Rust's own `{:.6}`
/// rounds exact ties to even: `0.0078125` is `0.007812`, MSVC gives `0.007813`).
///
/// UNVERIFIED: the MSVC behaviour is recalled from the runtime, not measured; values with up to
/// 15 significant digits (every sample) format identically either way.
pub fn msvc_fixed(x: f64, precision: usize) -> String {
    let neg = x.is_sign_negative();
    let sign = if neg { "-" } else { "" };
    if x == 0.0 {
        return if precision == 0 { format!("{sign}0") } else { format!("{sign}0.{}", "0".repeat(precision)) };
    }
    // d.dddddddddddddddde[-]N with 17 significant digits
    let s = format!("{:.16e}", x.abs());
    let (mant, exp) = s.split_once('e').expect("exponent form");
    let exp: i32 = exp.parse().expect("exponent");
    let digits: Vec<u8> = mant.bytes().filter(u8::is_ascii_digit).map(|b| b - b'0').collect();
    let point = exp + 1; // digits before the decimal point
    let (mut int, mut frac): (Vec<u8>, Vec<u8>) = if point >= digits.len() as i32 {
        let mut i = digits.clone();
        i.extend(std::iter::repeat_n(0, point as usize - digits.len()));
        (i, Vec::new())
    } else if point > 0 {
        (digits[..point as usize].to_vec(), digits[point as usize..].to_vec())
    } else {
        let mut f = vec![0; (-point) as usize];
        f.extend_from_slice(&digits);
        (vec![0], f)
    };
    let round_up = frac.get(precision).is_some_and(|&d| d >= 5);
    frac.truncate(precision);
    while frac.len() < precision {
        frac.push(0);
    }
    if round_up {
        let mut carry = true;
        for d in frac.iter_mut().rev().chain(int.iter_mut().rev()) {
            if *d == 9 {
                *d = 0;
            } else {
                *d += 1;
                carry = false;
                break;
            }
        }
        if carry {
            int.insert(0, 1);
        }
    }
    let int_s: String = {
        let t: String = int.iter().map(|d| (b'0' + d) as char).collect();
        let t = t.trim_start_matches('0');
        if t.is_empty() { "0".to_string() } else { t.to_string() }
    };
    let frac_s: String = frac.iter().map(|d| (b'0' + d) as char).collect();
    if precision == 0 { format!("{sign}{int_s}") } else { format!("{sign}{int_s}.{frac_s}") }
}

/// `CLIFileBasic::WriteDouble`: `|x| < 1e-10` is `0.0`; below `1e-6` it is `%12.10f`; else `%f`.
pub fn format_double(x: f64) -> Result<String, ChfError> {
    if !x.is_finite() {
        return Err(ChfError::new(format!("cannot write non-finite value {x}"), 3, None));
    }
    let ax = x.abs();
    Ok(if ax < 1e-10 {
        "0.0".to_string()
    } else if ax < 1e-6 {
        format!("{:>12}", msvc_fixed(x, 10))
    } else {
        msvc_fixed(x, 6)
    })
}

/// `CLIFileBasic::WritePoint`: `%f,%f`, no zero special case.
pub fn format_point(p: Point) -> Result<String, ChfError> {
    if !(p.x.is_finite() && p.y.is_finite()) {
        return Err(ChfError::new("cannot write a non-finite point", 3, None));
    }
    Ok(format!("{},{}", msvc_fixed(p.x, 6), msvc_fixed(p.y, 6)))
}

