//! Reader and writer for Mlaser `.chf` craft/job files (MCC-02).
//!
//! `.chf` is a plain-text, CRLF-terminated, one-value-per-line container that starts with the line
//! `scFlie` (sic) and a format version and ends with `eof`. Strings are Windows code page 936. The
//! grammar below is ported from the owner's own analysis (`03-chf-format.md`) and from the owner's
//! Python reader and writer (`nexcut.io.chf`, `nexcut.model`), which reproduce the shipped v4
//! samples byte for byte. Units are millimetres, angles radians, Y up.
//!
//! Scope and limits:
//!
//! * Versions 1 to 5 are read and written. Version 5 is what the vendor program writes. Versions
//!   2 to 4 carry blank "reserved" lines: they are consumed on read and written back as blank
//!   lines, so a file whose reserved lines are not blank does not round-trip byte for byte (no
//!   shipped sample has any).
//! * The cached geometry of a contour (`length`, bounding box, start and end point) is stored as
//!   given. [`Contour::from_elements`] recomputes it for segments, arcs, circles, ellipse arcs,
//!   points and polylines; splines must be given their cached values by the caller.
//! * Link records of a contour-ex graph keep their raw point tokens so a read/write cycle is
//!   byte-identical.
//! * Numbers are written with six decimals (`%f`), so a value read back may differ from the one
//!   written in the seventh decimal; writing what was read is byte-identical.
//! * Layer parameters (speed, power, gas, pierce) are **not** stored in a `.chf`; a contour only
//!   carries a layer index. See [`crate::craft`] for the parameters.
//! * Text is stored as raw code-page-936 bytes ([`ChfText`]). Converting to and from Unicode needs
//!   the `cp936` feature; without it only ASCII converts.
//!
//! The golden tests in this module use files generated by this module itself and cross-checked
//! against the owner's Python writer; no vendor file is read or copied.

