/// A graph, type ids 8 to 12.
#[derive(Clone, Debug, PartialEq)]
pub enum Graph {
    /// Type 8.
    Contour(Contour),
    /// Type 9.
    Group(Group),
    /// Type 10.
    Text(Text),
    /// Type 11.
    Scan(Scan),
    /// Type 12.
    ContourEx(ContourEx),
}

impl Graph {
    /// Type id written to the file.
    pub fn type_id(&self) -> i32 {
        match self {
            Graph::Contour(_) => 8,
            Graph::Group(_) => 9,
            Graph::Text(_) => 10,
            Graph::Scan(_) => 11,
            Graph::ContourEx(_) => 12,
        }
    }

    /// Every contour inside this graph (children, scan paths and text outlines included).
    pub fn contours(&self) -> Vec<&Contour> {
        match self {
            Graph::Contour(c) => vec![c],
            Graph::Group(g) => g.children.iter().collect(),
            Graph::ContourEx(c) => c.group.children.iter().collect(),
            Graph::Scan(s) => s.group.children.iter().chain(s.paths.iter()).collect(),
            Graph::Text(t) => t.outline.iter().flat_map(|o| o.children.iter()).collect(),
        }
    }
}

