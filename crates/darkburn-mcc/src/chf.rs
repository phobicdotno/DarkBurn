/// Type 8: one connected tool path plus crafts.
#[derive(Clone, Debug, PartialEq)]
pub struct Contour {
    /// Geometric tolerance in mm (closure test).
    pub precision: f64,
    /// Path length in mm (cached).
    pub length: f64,
    /// Bounding box minimum (cached).
    pub bbox_min: Point,
    /// Bounding box maximum (cached).
    pub bbox_max: Point,
    /// Cut start (cached).
    pub start: Point,
    /// Cut end (cached).
    pub end: Point,
    /// Glyphs in path order.
    pub elements: Vec<ContourElement>,
    /// Layer index, 0-based.
    pub layer: i32,
    /// Unknown integer, only its parity is used by the vendor (default 1).
    pub int58: i32,
    /// Crafts.
    pub crafts: Crafts,
}

impl Contour {
    /// A contour with cached geometry recomputed from its glyphs. Fails for an empty list and for
    /// splines (set the cached fields by hand instead).
    pub fn from_elements(precision: f64, layer: i32, elements: Vec<ContourElement>) -> Result<Contour, ChfError> {
        let m = measure(&elements, 0.002).ok_or_else(|| ChfError::new("cannot measure this contour (empty or contains a spline)", 3, None))?;
        Ok(Contour {
            precision,
            length: m.length,
            bbox_min: m.bbox_min,
            bbox_max: m.bbox_max,
            start: m.start,
            end: m.end,
            elements,
            layer,
            int58: 1,
            crafts: Crafts::default(),
        })
    }

    /// Recompute the cached geometry from the glyphs. `None` if not possible.
    pub fn measured(&self, step: f64) -> Option<Measure> {
        measure(&self.elements, step)
    }
}

