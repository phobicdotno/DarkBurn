    #[test]
    fn cached_geometry_is_recomputed_for_common_glyphs() {
        let seg =
            Contour::from_elements(0.01, 2, vec![ContourElement::forward(Glyph::Segment { p0: p(395.33, 302.907), p1: p(677.258772, 339.284906) })])
                .unwrap();
        assert!((seg.length - 284.266045).abs() < 1e-5, "{}", seg.length);
        assert_eq!(seg.layer, 2);
        assert_eq!(seg.start, p(395.33, 302.907));
        assert_eq!(seg.bbox_max, p(677.258772, 339.284906));
        let circle =
            Contour::from_elements(0.1, 0, vec![ContourElement::forward(Glyph::Circle { center: p(47.440977, 47.440977), radius: 47.422977 })])
                .unwrap();
        assert!((circle.length - 297.967353).abs() < 0.05, "{}", circle.length);
        assert!((circle.start.x - 94.863954).abs() < 1e-6 && (circle.start.y - 47.440977).abs() < 1e-6);
        assert!((circle.bbox_min.x - 0.018).abs() < 1e-3);
        // a reversed glyph swaps start and end
        let rev = Contour::from_elements(0.01, 0, vec![ContourElement { glyph: Glyph::Segment { p0: p(0.0, 0.0), p1: p(3.0, 4.0) }, direction: -1 }])
            .unwrap();
        assert_eq!((rev.start, rev.end), (p(3.0, 4.0), p(0.0, 0.0)));
        assert!((rev.length - 5.0).abs() < 1e-12);
        // splines and empty lists cannot be measured
        assert!(Contour::from_elements(0.01, 0, vec![]).is_err());
        let sp = Glyph::Spline { int1: 0, int2: 0, control_points: vec![p(0.0, 0.0); 4], knots: vec![0.0; 8] };
        assert!(Contour::from_elements(0.01, 0, vec![ContourElement::forward(sp)]).is_err());
        // a point drill
        let pt = Contour::from_elements(0.01, 0, vec![ContourElement::forward(Glyph::Point(p(5.0, 6.0)))]).unwrap();
        assert_eq!((pt.length, pt.start, pt.end), (0.0, p(5.0, 6.0), p(5.0, 6.0)));
    }

