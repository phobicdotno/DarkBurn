    #[test]
    fn text_bytes_round_trip_raw() {
        // 宋体 as code page 936 bytes, the default font name
        assert_eq!(Text::default().font.as_bytes(), &[0xCB, 0xCE, 0xCC, 0xE5]);
        let t = Text { text: ChfText::from_bytes(vec![0xBC, 0xA4, 0xB9, 0xE2, b'A', 0x80, 0xFF]), ..Text::default() };
        let doc = ChfDocument { graphs: vec![Graph::Text(t.clone())], ..ChfDocument::default() };
        let data = write_chf(&doc).unwrap();
        assert!(data.windows(7).any(|w| w == [0xBC, 0xA4, 0xB9, 0xE2, b'A', 0x80, 0xFF]));
        let back = read_chf(&data, true).unwrap();
        assert_eq!(back, doc);
        // non-ASCII conversion needs the feature
        #[cfg(not(feature = "cp936"))]
        {
            assert!(ChfText::from_text("激光").is_err());
            assert_eq!(ChfText::from_text("ABC").unwrap().to_text(), "ABC");
        }
    }

    #[cfg(feature = "cp936")]
    #[test]
    fn chinese_text_round_trips_through_cp936() {
        // 激光 = 0xBC 0xA4 0xB9 0xE2; 宋体 = 0xCB 0xCE 0xCC 0xE5
        let t = ChfText::from_text("激光ABC").unwrap();
        assert_eq!(t.as_bytes(), &[0xBC, 0xA4, 0xB9, 0xE2, b'A', b'B', b'C']);
        assert_eq!(t.to_text(), "激光ABC");
        assert_eq!(Text::default().font.to_text(), "宋体");
        assert!(ChfText::from_text("\u{1F600}").is_err(), "emoji has no code page 936 mapping");
        let doc = ChfDocument { graphs: vec![Graph::Text(Text { text: t, ..Text::default() })], ..ChfDocument::default() };
        let data = write_chf(&doc).unwrap();
        assert_eq!(read_chf(&data, true).unwrap(), doc);
    }
