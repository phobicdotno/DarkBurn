/// A glyph, type ids 1 to 7.
#[derive(Clone, Debug, PartialEq)]
pub enum Glyph {
    /// Type 1: one point (drill / pierce).
    Point(Point),
    /// Type 2: straight line.
    Segment {
        /// Start.
        p0: Point,
        /// End.
        p1: Point,
    },
    /// Type 3: circular arc; sweep is `end_angle - start_angle`, positive counter-clockwise.
    Arc {
        /// Centre.
        center: Point,
        /// Radius.
        radius: f64,
        /// Start angle, radians.
        start_angle: f64,
        /// End angle, radians.
        end_angle: f64,
    },
    /// Type 4: full circle, starts at angle 0 and runs counter-clockwise.
    Circle {
        /// Centre.
        center: Point,
        /// Radius.
        radius: f64,
    },
    /// Type 5: DXF-style ellipse arc.
    EllipseArc {
        /// Centre.
        center: Point,
        /// Major axis vector relative to the centre.
        major_axis: Point,
        /// Minor over major.
        ratio: f64,
        /// Start parameter, radians.
        start_param: f64,
        /// End parameter, radians.
        end_param: f64,
    },
    /// Type 6: lightweight polyline. `closed` is the raw integer (1 = closed).
    LwPolyline {
        /// Closed flag.
        closed: i32,
        /// Vertices.
        vertices: Vec<LwVertex>,
    },
    /// Type 7: cubic B-spline without weights. The two integers are unknown flags kept opaque.
    Spline {
        /// Unknown flag.
        int1: i32,
        /// Unknown flag.
        int2: i32,
        /// Control points (at least 4).
        control_points: Vec<Point>,
        /// Knots (control points + 4).
        knots: Vec<f64>,
    },
}

impl Glyph {
    /// Type id written to the file.
    pub fn type_id(&self) -> i32 {
        match self {
            Glyph::Point(_) => 1,
            Glyph::Segment { .. } => 2,
            Glyph::Arc { .. } => 3,
            Glyph::Circle { .. } => 4,
            Glyph::EllipseArc { .. } => 5,
            Glyph::LwPolyline { .. } => 6,
            Glyph::Spline { .. } => 7,
        }
    }
}

