fn atoi(tok: &[u8]) -> i32 {
    // strtol prefix rule: optional '-', then digits; saturate at the 32-bit limits.
    let (neg, digits) = match tok.first() {
        Some(b'-') => (true, &tok[1..]),
        _ => (false, tok),
    };
    let mut v: i64 = 0;
    let mut any = false;
    for &b in digits {
        if !b.is_ascii_digit() {
            break;
        }
        any = true;
        v = (v * 10 + (b - b'0') as i64).min(1 << 40);
    }
    if !any {
        return 0;
    }
    let v = if neg { -v } else { v };
    v.clamp(i32::MIN as i64, i32::MAX as i64) as i32
}

fn atof(tok: &[u8]) -> f64 {
    // longest prefix of -?(\d+\.?\d*|\.\d+)
    let mut i = 0;
    if tok.first() == Some(&b'-') {
        i = 1;
    }
    let ds = i;
    while i < tok.len() && tok[i].is_ascii_digit() {
        i += 1;
    }
    let int_digits = i - ds;
    let mut end = i;
    if i < tok.len() && tok[i] == b'.' {
        let mut j = i + 1;
        while j < tok.len() && tok[j].is_ascii_digit() {
            j += 1;
        }
        let frac_digits = j - i - 1;
        if int_digits > 0 || frac_digits > 0 {
            end = j;
        }
    }
    if int_digits == 0 && end == i {
        return 0.0;
    }
    std::str::from_utf8(&tok[..end]).ok().and_then(|s| s.parse::<f64>().ok()).unwrap_or(0.0)
}

fn valid_int(tok: &[u8]) -> bool {
    tok.iter().all(|&b| b.is_ascii_digit() || b == b'-')
}

fn valid_double(tok: &[u8]) -> bool {
    tok.iter().all(|&b| b.is_ascii_digit() || b == b'-' || b == b'.') && tok.iter().filter(|&&b| b == b'.').count() <= 1
}

fn strip_blanks(s: &str) -> Vec<u8> {
    s.bytes().filter(|&b| b != b' ' && b != b'\t').collect()
}

struct Tokens {
    toks: Vec<Vec<u8>>,
    line: usize,
    strict: bool,
}

impl Tokens {
    /// `ReadToken`: one token per line, CR, LF or CRLF terminate it, spaces and tabs are dropped
    /// anywhere in the line, an empty line is an empty token.
    fn new(data: &[u8], strict: bool) -> Tokens {
        let mut toks = Vec::new();
        let mut cur: Vec<u8> = Vec::new();
        let mut started = false;
        let mut i = 0;
        while i < data.len() {
            let b = data[i];
            match b {
                b'\r' | b'\n' => {
                    toks.push(std::mem::take(&mut cur));
                    started = false;
                    if b == b'\r' && data.get(i + 1) == Some(&b'\n') {
                        i += 1;
                    }
                }
                b' ' | b'\t' => started = true,
                _ => {
                    cur.push(b);
                    started = true;
                }
            }
            i += 1;
        }
        if started {
            toks.push(cur);
        }
        Tokens { toks, line: 0, strict }
    }

    fn tok(&mut self) -> Result<&[u8], ChfError> {
        let i = self.line;
        self.line += 1;
        self.toks.get(i).map(|v| v.as_slice()).ok_or_else(|| ChfError::new("unexpected end of file", 4, Some(i + 1)))
    }

    fn int(&mut self) -> Result<i32, ChfError> {
        let i = self.line;
        let t = self.tok()?;
        if !valid_int(t) {
            return Err(ChfError::new(format!("expected int, got {:?}", String::from_utf8_lossy(t)), 3, Some(i + 1)));
        }
        Ok(atoi(t))
    }

    fn double(&mut self) -> Result<f64, ChfError> {
        let i = self.line;
        let t = self.tok()?;
        if !valid_double(t) {
            return Err(ChfError::new(format!("expected double, got {:?}", String::from_utf8_lossy(t)), 3, Some(i + 1)));
        }
        Ok(atof(t))
    }

    fn bool(&mut self) -> Result<bool, ChfError> {
        let i = self.line;
        let t = self.tok()?;
        if !valid_int(t) {
            return Err(ChfError::new(format!("expected bool, got {:?}", String::from_utf8_lossy(t)), 3, Some(i + 1)));
        }
        Ok(t == b"1")
    }

    fn point_from(t: &[u8], line: usize) -> Result<Point, ChfError> {
        let bad = || ChfError::new(format!("expected 'x,y', got {:?}", String::from_utf8_lossy(t)), 3, Some(line));
        let comma = t.iter().position(|&b| b == b',').ok_or_else(bad)?;
        let (mut xs, mut ys) = (&t[..comma], &t[comma + 1..]);
        if xs.len() > POINT_HALF_MAX {
            xs = b"0";
        }
        if ys.len() > POINT_HALF_MAX {
            ys = b"0";
        }
        if !valid_double(xs) || !valid_double(ys) {
            return Err(bad());
        }
        Ok(Point::new(atof(xs), atof(ys)))
    }

    fn point(&mut self) -> Result<Point, ChfError> {
        let i = self.line;
        let t = self.tok()?.to_vec();
        Tokens::point_from(&t, i + 1)
    }

    fn wstr(&mut self) -> Result<ChfText, ChfError> {
        Ok(ChfText(self.tok()?.to_vec()))
    }

    fn marker(&mut self, marker: &str) -> Result<(), ChfError> {
        let i = self.line;
        let strict = self.strict;
        let t = self.tok()?;
        if strict && t != strip_blanks(marker).as_slice() {
            return Err(ChfError::new(format!("expected {marker:?}, got {:?}", String::from_utf8_lossy(t)), 3, Some(i + 1)));
        }
        Ok(())
    }

    fn header(&mut self, prefix: &str) -> Result<(), ChfError> {
        let i = self.line;
        let strict = self.strict;
        let t = self.tok()?;
        if strict && !t.starts_with(&strip_blanks(prefix)) {
            return Err(ChfError::new(format!("expected {prefix:?}, got {:?}", String::from_utf8_lossy(t)), 3, Some(i + 1)));
        }
        Ok(())
    }

    fn reserved(&mut self, n: usize) -> Result<(), ChfError> {
        if self.line + n > self.toks.len() {
            self.line = self.toks.len();
            return Err(ChfError::new("unexpected end of file", 4, Some(self.line + 1)));
        }
        self.line += n;
        Ok(())
    }
}

fn legacy(version: i32) -> bool {
    (2..=4).contains(&version)
}

fn read_glyph(tk: &mut Tokens, gtype: i32) -> Result<Glyph, ChfError> {
    Ok(match gtype {
        1 => Glyph::Point(tk.point()?),
        2 => Glyph::Segment { p0: tk.point()?, p1: tk.point()? },
        3 => Glyph::Arc { center: tk.point()?, radius: tk.double()?, start_angle: tk.double()?, end_angle: tk.double()? },
        4 => Glyph::Circle { center: tk.point()?, radius: tk.double()? },
        5 => Glyph::EllipseArc {
            center: tk.point()?,
            major_axis: tk.point()?,
            ratio: tk.double()?,
            start_param: tk.double()?,
            end_param: tk.double()?,
        },
        6 => {
            let closed = tk.int()?;
            let n = tk.int()?;
            let mut vertices = Vec::new();
            for _ in 0..n.max(0) {
                let pt = tk.point()?;
                vertices.push(LwVertex { pt, bulge: tk.double()? });
            }
            Glyph::LwPolyline { closed, vertices }
        }
        7 => {
            let int1 = tk.int()?;
            let int2 = tk.int()?;
            let n = tk.int()?;
            let mut control_points = Vec::new();
            for _ in 0..n.max(0) {
                control_points.push(tk.point()?);
            }
            let nk = tk.int()?;
            let mut knots = Vec::new();
            for _ in 0..nk.max(0) {
                knots.push(tk.double()?);
            }
            if n < 4 || nk != n + 4 {
                return Err(ChfError::new(format!("spline needs >=4 control points and n+4 knots (n={n}, knots={nk})"), 3, Some(tk.line)));
            }
            Glyph::Spline { int1, int2, control_points, knots }
        }
        other => return Err(ChfError::new(format!("unknown glyph type {other}"), 3, Some(tk.line))),
    })
}

fn read_contour(tk: &mut Tokens, version: i32) -> Result<Contour, ChfError> {
    let precision = tk.double()?;
    tk.marker(GLYPHS)?;
    if legacy(version) {
        tk.reserved(LEGACY_BLANKS_GLYPHS)?;
    }
    let length = tk.double()?;
    let bbox_min = tk.point()?;
    let bbox_max = tk.point()?;
    let start = tk.point()?;
    let end = tk.point()?;
    let n = tk.int()?;
    if n < 1 {
        return Err(ChfError::new(format!("contour with {n} glyphs"), 3, Some(tk.line)));
    }
    let mut elements = Vec::new();
    for _ in 0..n {
        tk.header(GLY)?;
        let direction = tk.int()?;
        let gtype = tk.int()?;
        let glyph = read_glyph(tk, gtype)?;
        elements.push(ContourElement { glyph, direction });
        if legacy(version) {
            tk.reserved(LEGACY_BLANKS_PER_GLYPH)?;
        }
    }
    tk.marker(END_GLYPHS)?;
    let layer = tk.int()?;
    let int58 = tk.int()?;
    tk.marker(CRAFTS)?;
    if legacy(version) {
        tk.reserved(LEGACY_BLANKS_CRAFTS)?;
    }
    let compensate_type = tk.int()?;
    let compensate_width = tk.double()?;
    tk.marker(PWM)?;
    let pwm_enable = tk.int()?;
    let npwm = tk.int()?;
    let mut pwm_nodes = Vec::new();
    for _ in 0..npwm.max(0) {
        let a = tk.double()?;
        pwm_nodes.push((a, tk.double()?));
    }
    let nclose = tk.int()?;
    let mut pwm_close_pos_ratios = Vec::new();
    for _ in 0..nclose.max(0) {
        pwm_close_pos_ratios.push(tk.double()?);
    }
    tk.marker(END_PWM)?;
    let double170 = tk.double()?;
    let double188 = tk.double()?;
    tk.marker(GUIDE)?;
    let kind = tk.int()?;
    let angle_deg = tk.double()?;
    let llength = tk.double()?;
    let arc_radius = if version > 1 { Some(tk.double()?) } else { None };
    let flag = tk.bool()?;
    tk.marker(END_GUIDE)?;
    let cool_pos = if version > 2 {
        tk.marker(COOL)?;
        let ncool = tk.int()?;
        let mut v = Vec::new();
        for _ in 0..ncool.max(0) {
            v.push(tk.double()?);
        }
        tk.marker(END_COOL)?;
        Some(v)
    } else {
        None
    };
    tk.marker(END_CRAFTS)?;
    Ok(Contour {
        precision,
        length,
        bbox_min,
        bbox_max,
        start,
        end,
        elements,
        layer,
        int58,
        crafts: Crafts {
            compensate_type,
            compensate_width,
            pwm_enable,
            pwm_nodes,
            pwm_close_pos_ratios,
            double170,
            double188,
            lead_line: LeadLine { kind, angle_deg, length: llength, arc_radius, flag },
            cool_pos,
        },
    })
}

fn read_group(tk: &mut Tokens, version: i32) -> Result<Group, ChfError> {
    if legacy(version) {
        tk.reserved(LEGACY_BLANKS_GROUP)?;
    }
    let length = tk.double()?;
    let bbox_min = tk.point()?;
    let bbox_max = tk.point()?;
    let start = tk.point()?;
    let end = tk.point()?;
    let n = tk.int()?;
    let mut children = Vec::new();
    for _ in 0..n.max(0) {
        tk.header(GROUP_ELEM)?;
        children.push(read_contour(tk, version)?);
    }
    let layer = tk.int()?;
    let int58 = tk.int()?;
    Ok(Group { length, bbox_min, bbox_max, start, end, children, layer, int58 })
}

fn read_contour_ex(tk: &mut Tokens, version: i32) -> Result<ContourEx, ChfError> {
    let group = read_group(tk, version)?;
    let n = tk.int()?;
    let mut links = Vec::new();
    for _ in 0..n.max(0) {
        tk.header(LINK_INFO)?;
        let (int0, int4) = (tk.int()?, tk.int()?);
        let (d8, d10, d38, d40) = (tk.double()?, tk.double()?, tk.double()?, tk.double()?);
        let line1 = tk.line + 1;
        let t18 = tk.tok()?.to_vec();
        let pt18 = link_point(&t18, int0 == 1, line1)?;
        let line2 = tk.line + 1;
        let t28 = tk.tok()?.to_vec();
        let pt28 = link_point(&t28, int4 == 1, line2)?;
        links.push(LinkInfo {
            int0,
            int4,
            d8,
            d10,
            d38,
            d40,
            pt18,
            pt28,
            pt18_token: Some(t18.iter().map(|&b| b as char).collect()),
            pt28_token: Some(t28.iter().map(|&b| b as char).collect()),
        });
    }
    Ok(ContourEx { group, links })
}

fn link_point(tok: &[u8], parsed_by_vendor: bool, line: usize) -> Result<Point, ChfError> {
    match Tokens::point_from(tok, line) {
        Ok(p) => Ok(p),
        Err(e) if parsed_by_vendor => Err(e),
        Err(_) => Ok(Point::new(0.0, 0.0)),
    }
}

fn read_scan(tk: &mut Tokens, version: i32) -> Result<Scan, ChfError> {
    let group = read_group(tk, version)?;
    tk.marker(SCAN_PATH)?;
    if legacy(version) {
        tk.reserved(LEGACY_BLANKS_SCAN)?;
    }
    let n = tk.int()?;
    let mut paths = Vec::new();
    for _ in 0..n.max(0) {
        tk.header(SCAN_PATH_NO)?;
        paths.push(read_contour(tk, version)?);
    }
    tk.marker(END_SCAN_PATH)?;
    Ok(Scan { group, paths })
}

fn read_text(tk: &mut Tokens, version: i32) -> Result<Text, ChfError> {
    if legacy(version) {
        tk.reserved(LEGACY_BLANKS_TEXT)?;
    }
    let position = tk.point()?;
    let (d130, d138, d140) = (tk.double()?, tk.double()?, tk.double()?);
    let text = tk.wstr()?;
    tk.marker(TEXT_PARA)?;
    let font = tk.wstr()?;
    let (font_d0, font_d1, font_d2) = (tk.double()?, tk.double()?, tk.double()?);
    tk.marker(END_TEXT_PARA)?;
    let (outline, layer, int58) = if version >= 4 {
        let g = read_group(tk, version)?;
        let (l, i) = (g.layer, g.int58);
        (Some(g), l, i)
    } else {
        let l = tk.int()?;
        (None, l, tk.int()?)
    };
    Ok(Text { position, d130, d138, d140, text, font, font_d0, font_d1, font_d2, outline, layer, int58 })
}

/// Parse `.chf` bytes. With `strict` the marker and header lines and the final `eof` token are
/// checked; the vendor reader only checks the magic and the file tail.
pub fn read_chf(data: &[u8], strict: bool) -> Result<ChfDocument, ChfError> {
    if data.is_empty() {
        return Err(ChfError::new("empty file", 2, None));
    }
    // Walk back over bytes whose signed value is <= 0x0d (CR, LF, NUL and every byte >= 0x80),
    // then require "eof", like the vendor open routine.
    let mut end = data.len();
    while end > 0 && (data[end - 1] <= 0x0D || data[end - 1] >= 0x80) {
        end -= 1;
    }
    let mut tk = Tokens::new(data, strict);
    if tk.tok().map_err(|_| ChfError::new("missing 'scFlie' magic", 5, Some(1)))? != MAGIC.as_bytes() {
        return Err(ChfError::new("missing 'scFlie' magic", 5, Some(1)));
    }
    if end < 3 || &data[end - 3..end] != b"eof" {
        return Err(ChfError::new("file does not end with 'eof'", 4, None));
    }
    let mut doc = ChfDocument { version: tk.int()?, ..ChfDocument::default() };
    tk.marker(BEGIN_GRAPHS)?;
    if legacy(doc.version) {
        tk.reserved(LEGACY_BLANKS_BEGIN_GRAPHS)?;
    }
    let n = tk.int()?;
    for _ in 0..n.max(0) {
        tk.header(GRAPH_NO)?;
        let gtype = tk.int()?;
        let g = match gtype {
            8 => Graph::Contour(read_contour(&mut tk, doc.version)?),
            9 => Graph::Group(read_group(&mut tk, doc.version)?),
            10 => Graph::Text(read_text(&mut tk, doc.version)?),
            11 => Graph::Scan(read_scan(&mut tk, doc.version)?),
            12 => Graph::ContourEx(read_contour_ex(&mut tk, doc.version)?),
            other => return Err(ChfError::new(format!("unknown graph type {other}"), 3, Some(tk.line))),
        };
        doc.graphs.push(g);
    }
    tk.marker(END_GRAPHS)?;
    doc.trailer_bool = tk.bool()?;
    doc.trailer_double = tk.double()?;
    doc.trailer_pt1 = tk.point()?;
    doc.trailer_pt2 = tk.point()?;
    if strict {
        let line = tk.line + 1;
        let t = tk.tok()?;
        if t != EOF_MARK.as_bytes() {
            return Err(ChfError::new(format!("expected 'eof', got {:?}", String::from_utf8_lossy(t)), 4, Some(line)));
        }
    }
    Ok(doc)
}

