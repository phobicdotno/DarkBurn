/// A read or write error. `code` follows the vendor reader: 1 open failed, 2 empty, 3 parse error,
/// 4 missing `eof` / unexpected end, 5 bad magic.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ChfError {
    /// What went wrong.
    pub message: String,
    /// Vendor error code.
    pub code: u8,
    /// 1-based line, if known.
    pub line: Option<usize>,
}

impl ChfError {
    fn new(message: impl Into<String>, code: u8, line: Option<usize>) -> ChfError {
        ChfError { message: message.into(), code, line }
    }
}

impl fmt::Display for ChfError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self.line {
            Some(l) => write!(f, "line {l}: {} (code {})", self.message, self.code),
            None => write!(f, "{} (code {})", self.message, self.code),
        }
    }
}

impl std::error::Error for ChfError {}

/// A string in a `.chf`: raw code-page-936 bytes.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct ChfText(Vec<u8>);

impl ChfText {
    /// Raw bytes as stored in the file.
    pub fn from_bytes(bytes: Vec<u8>) -> ChfText {
        ChfText(bytes)
    }

    /// The stored bytes.
    pub fn as_bytes(&self) -> &[u8] {
        &self.0
    }

    /// Convert from Unicode. Without the `cp936` feature only ASCII is accepted. A character the
    /// code page cannot represent is an error (the vendor would write `?`).
    pub fn from_text(s: &str) -> Result<ChfText, ChfError> {
        if s.contains(['\r', '\n']) {
            return Err(ChfError::new("string contains a line break", 3, None));
        }
        if s.is_ascii() {
            return Ok(ChfText(s.as_bytes().to_vec()));
        }
        #[cfg(feature = "cp936")]
        {
            let (bytes, _, had_errors) = encoding_rs::GBK.encode(s);
            if had_errors {
                return Err(ChfError::new("character not representable in code page 936", 3, None));
            }
            Ok(ChfText(bytes.into_owned()))
        }
        #[cfg(not(feature = "cp936"))]
        Err(ChfError::new("non-ASCII text needs the `cp936` feature", 3, None))
    }

    /// Convert to Unicode. Without the `cp936` feature, non-ASCII bytes become U+FFFD.
    pub fn to_text(&self) -> String {
        #[cfg(feature = "cp936")]
        {
            encoding_rs::GBK.decode_without_bom_handling(&self.0).0.into_owned()
        }
        #[cfg(not(feature = "cp936"))]
        {
            self.0.iter().map(|&b| if b.is_ascii() { b as char } else { '\u{FFFD}' }).collect()
        }
    }
}

